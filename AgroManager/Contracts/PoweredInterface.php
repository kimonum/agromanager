<?php

/**
 * Контракт для любого объекта, который может быть заправлен топливос
 * Гарантирует, что у наследников будет единый интерфейс для работы с энергией
 */
interface PoweredInterface
{
    /**
     * Заправка объекта
     * Количество единиц топлива. Должно быть положительным
     */
    public function refuel(float $units): void;
    
    /**
     * Получение текущего уровня топлива в процентах
     * Значение от 0.0 до 100.0
     */
    public function getPercentage(): float;
}